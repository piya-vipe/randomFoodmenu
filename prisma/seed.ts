async function main() {
  const keepSlugs = CATEGORIES.map((c) => c.slug);

  // Remove categories that are no longer part of the menu (cascades to their menu items/picks).
  await prisma.category.deleteMany({
    where: { slug: { notIn: keepSlugs } },
  });

  for (const cat of CATEGORIES) {
    const category = await prisma.category.upsert({
      where: { slug: cat.slug },
      update: { name: cat.name, emoji: cat.emoji, order: cat.order },
      create: {
        slug: cat.slug,
        name: cat.name,
        emoji: cat.emoji,
        order: cat.order,
      },
    });

    const keepNames = cat.items.map((item) => item.name);

    // Remove menu items that were trimmed from this category (cascades to picks).
    await prisma.menuItem.deleteMany({
      where: { categoryId: category.id, name: { notIn: keepNames } },
    });

    for (const item of cat.items) {
      await prisma.menuItem.upsert({
        where: {
          categoryId_name: {
            categoryId: category.id,
            name: item.name,
          },
        },
        update: { howTo: item.howTo },
        create: {
          name: item.name,
          howTo: item.howTo,
          categoryId: category.id,
        },
      });
    }
  }

  console.log(
    `Seeded ${CATEGORIES.length} categories and ${CATEGORIES.reduce(
      (sum, c) => sum + c.items.length,
      0
    )} menu items.`
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

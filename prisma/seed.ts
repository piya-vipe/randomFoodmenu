async function main() {
  const keepSlugs = CATEGORIES.map((c) => c.slug);

  // Only prune SEED-managed rows — categories added by hand through /admin stay put.
  await prisma.category.deleteMany({
    where: { source: "SEED", slug: { notIn: keepSlugs } },
  });

  for (const cat of CATEGORIES) {
    const category = await prisma.category.upsert({
      where: { slug: cat.slug },
      update: { name: cat.name, emoji: cat.emoji, order: cat.order },
      create: {
        slug: cat.slug,
        name: cat.name,
        emoji: cat.emoji,
        order: cat.order,
        source: "SEED",
      },
    });

    const keepNames = cat.items.map((item) => item.name);

    // Likewise, never delete manually-added menu items.
    await prisma.menuItem.deleteMany({
      where: {
        categoryId: category.id,
        source: "SEED",
        name: { notIn: keepNames },
      },
    });

    for (const item of cat.items) {
      await prisma.menuItem.upsert({
        where: {
          categoryId_name: {
            categoryId: category.id,
            name: item.name,
          },
        },
        update: {
          steps: item.steps,
          ingredients: item.ingredients,
          servingSize: item.servingSize,
        },
        create: {
          name: item.name,
          steps: item.steps,
          ingredients: item.ingredients,
          servingSize: item.servingSize,
          categoryId: category.id,
          source: "SEED",
        },
      });
    }
  }

  console.log(
    `Seeded ${CATEGORIES.length} categories and ${CATEGORIES.reduce(
      (sum, c) => sum + c.items.length,
      0
    )} menu items.`
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
